from typing import Any, Optional

from .base import BaseAgent


class ReplanningAgent(BaseAgent):
    """Builds a versioned replanning proposal. It can only record SIMULATED failures; real failures come
    from a coordinator. A proposal never replaces the original plan until a human approves it."""
    name = "REPLANNING_AGENT"
    allowed_tools = frozenset({"report_supplier_failure", "get_affected_allocations", "find_alternative_suppliers",
                               "generate_replanning_proposal", "get_replanning_history", "get_procurement_plan"})

    async def simulate_failure(self, scenario: dict[str, Any]) -> dict[str, Any]:
        return (await self.call("report_supplier_failure", workflow_id=self.workflow_id, **scenario))["event"]

    async def assess(self, failure_event_id: str) -> dict[str, Any]:
        return await self.call("get_affected_allocations", failure_event_id=failure_event_id)

    async def alternatives(self, emergency_id: str, vendor_id: str) -> dict[str, Any]:
        return await self.call("find_alternative_suppliers", emergency_id=emergency_id, exclude_vendor_id=vendor_id)

    async def propose(self, plan_id: str, failure_event_id: Optional[str], budget: Optional[float],
                      max_delivery_days: Optional[int], attempt: int) -> dict[str, Any]:
        return await self.call("generate_replanning_proposal", source_plan_id=plan_id, failure_event_id=failure_event_id,
                               budget=budget, max_delivery_days=max_delivery_days,
                               rationale=f"Generated by the Replanning Agent (attempt {attempt}).",
                               workflow_id=f"{self.workflow_id}:a{attempt}" if self.workflow_id else None)
